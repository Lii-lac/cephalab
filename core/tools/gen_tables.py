"""Generate core/src/gen/tables.h from data/BrandTraitsParam.raw.json.

Ability order comes from s3seed/seedmath.py (ABILITY_ORDER), the reference roll math.
Re-run after the data changes:  python core/tools/gen_tables.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from s3seed.seedmath import ABILITY_ORDER  # noqa: E402

SRC = ROOT / "data" / "BrandTraitsParam.raw.json"
OUT = ROOT / "core" / "src" / "gen" / "tables.h"


def main() -> None:
    raw = json.loads(SRC.read_text(encoding="utf-8"))
    unusual_w, normal_w, usual_w = raw["SkillEasilyToGetParam"]
    traits = raw["Traits"]
    if "None" not in traits:
        raise SystemExit("BrandTraitsParam has no None row")

    def idx(name: str) -> int:
        if name == "None":
            return -1
        if name not in ABILITY_ORDER:
            raise SystemExit(f"unknown ability {name!r}")
        return ABILITY_ORDER.index(name)

    codes = list(traits.keys())
    rows = [f'    {{"{c}", {idx(traits[c]["UnusualGearSkill"])}, {idx(traits[c]["UsualGearSkill"])}}},' for c in codes]
    names = ",\n".join(f'    "{a}"' for a in ABILITY_ORDER)
    max_w = max(unusual_w, normal_w, usual_w)
    text = f"""// Generated by core/tools/gen_tables.py from data/BrandTraitsParam.raw.json. Do not edit.
#pragma once
#include <cstdint>

namespace st::gen {{

inline constexpr int kAbilityCount = {len(ABILITY_ORDER)};
inline constexpr const char* kAbilityNames[kAbilityCount] = {{
{names},
}};

// SkillEasilyToGetParam: unusual, normal, usual.
inline constexpr uint32_t kWeightUnusual = {unusual_w};
inline constexpr uint32_t kWeightNormal = {normal_w};
inline constexpr uint32_t kWeightUsual = {usual_w};
inline constexpr uint32_t kMaxTotal = {len(ABILITY_ORDER) * max_w};

struct BrandRow {{
    const char* code;
    int8_t unusual;  // ability index, -1 = None
    int8_t usual;
}};

inline constexpr BrandRow kBrands[] = {{
{chr(10).join(rows)}
}};
inline constexpr int kBrandCount = {len(codes)};
inline constexpr int kNoneBrand = {codes.index("None")};

}}  // namespace st::gen
"""
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(codes)} brands, {len(ABILITY_ORDER)} abilities")


if __name__ == "__main__":
    main()
